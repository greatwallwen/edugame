P8_DH = """同学们好，这一节我们做 ADC 的反向兄弟——DAC（数模转换器）。如果说 ADC 让 STM32 看见模拟世界，DAC 就是让 STM32 输出真正连续的模拟信号。前一节我们用 PWM + RC 滤波模拟了模拟输出，但那是间接做法、有纹波、频响有限。STM32F1 系列的部分型号（F103ZE、F103VE、F103RC 以上）内置了真正的 12 位 DAC——VAA 在外参考下精度可达 ±10mV，做信号发生、波形输出、参考电压就更专业了。

DAC 的核心数学非常简单：V_out = V_ref × (DOR / 4095)，DOR 是 DAC 数据寄存器的值（0~4095），V_ref 通常是 VAA。比如 V_ref = 3.3V，DOR = 2048，那 V_out 就接近 1.65V。这跟 ADC 的反推公式正好镜像——一个把数字变模拟，一个把模拟变数字。两个外设结合起来你就能在 STM32 上做完整的信号链：ADC 采样输入信号、CPU 做数字处理、DAC 输出处理后的模拟信号。这是 DSP（数字信号处理）的硬件基础，从这里你可以走向音频处理、电机控制、医学仪器等数十个细分领域。

DAC 输出信号有四种典型方式，难度从低到高。第一是直接写 DAC->DHR12R1 寄存器或调 HAL_DAC_SetValue。这是最简单的——CPU 想输出什么写什么，但 CPU 占用高，难做高频波形。第二是定时器触发 DAC——DAC 内部有一个 trigger，配置 TIM6 / TIM7 周期触发，每次触发 DAC 自动从一个 buffer 取下一个值送出去。第三是 DAC + DMA + 定时器三件套——TIM 触发 DAC、DAC 触发 DMA、DMA 把内存里整段波形数组循环送给 DAC，CPU 完全不参与，可以稳定跑 1MSPS 的 DAC 输出。第四是 DAC + DMA + 双缓冲——更高级，做实时合成、调制、音频流播放都靠它。

——进阶补充——
DAC 输出最常见的应用是函数发生器：方波、三角波、正弦波、锯齿波。生成方法是预先在内存里建一张查找表（LUT），每个值对应该波形在某相位的 DAC 输出值。对正弦波来说这张表 256 项就够，每项是 sin(2π × i / 256) × 2047 + 2048。配合 DMA + 定时器后 DAC 自动循环输出这张表，频率由定时器控制——很简单的范式但威力巨大。这就是商业函数发生器的工作原理，区别只在分辨率（DAC 位数）、采样率（DAC 时钟）和品控（参考电压稳定性）。

DAC 还有个非常工程的应用：做参考电压源。许多场景需要一个软件可调的精密电压参考——比如电压、电流可调电源、运放偏置电压。用 STM32 内置 DAC + 一颗运放 buffer 就能做出 0~3.3V、12 位精度（约 0.8mV 步进）的可编程电压源。配合软件 PI 调节让输出电压精确等于设定值，外面接的运放 buffer 提供电流驱动能力——一个数字可控电源就出来了。这种把数字控制和模拟输出无缝衔接的能力是 STM32 这种 MCU 的核心价值之一。

最后聊 DAC 的几个工程坑。第一是 DAC 输出的最大电流只有几百微安，直接驱动 LED、扬声器都带不动——必须接运放 buffer。第二是 DAC 输出的 settling time 大约 3 微秒，意思是高频时无法跟上变化——超过 300kHz 的输出建议用专用 DAC 芯片。第三是 DAC 与 ADC 共用 VAA 时，ADC 高速采样会拉低 VAA 让 DAC 输出抖动。解决办法是把 VAA 单独走一条 LDO，或者干脆 DAC 用专用参考电压源。"""

