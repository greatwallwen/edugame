P9_DH = """同学们好，这一节我们把前面所有积累综合起来做一个真东西——多传感器环境监测系统。它能实时测温度、湿度、气压、空气质量，把数据通过 OLED 显示出来、也能通过 UART 上传到电脑或上位机。这种系统是现代物联网的最小单元——一个能感知环境、能联网、能本地反馈的智能节点，把千千万万这种节点连起来就是智慧农业、智慧城市、工业 4.0 的底层。从今天起你写的不再是练习题，是一个真正能用的东西。

硬件选型很有讲究。温湿度用 SHT30——I2C 接口、精度 ±2% 湿度、±0.3°C 温度、价格 5 元，是物联网温湿度传感器最普及的型号。气压用 BMP280——I2C 接口、精度 ±1hPa、自带温度补偿、价格 8 元。空气质量用 MQ135——模拟输出、能感知 NH3、苯、CO2 等，价格 15 元。OLED 选 SSD1306 0.96 寸 128 × 64——I2C 接口和上面两颗共用总线、3 元。这套硬件加起来不到 50 元，但能做的事跟商品级气象站差不多。

软件架构核心是定时器调度 + 状态机 + I2C 读传感器。TIM2 每秒中断一次置位 g_data_ready 标志；主循环检查标志置位时按顺序读 SHT30 → BMP280 → MQ135（ADC），把读数存入全局 sensor_data 结构体；OLED 刷新放主循环每 100ms 一次；UART 上传放每 10s 一次（不要太频繁，否则上位机过载）。这种分层调度让每个外设按自己节奏跑，互相不阻塞，是嵌入式多任务并行的最朴素实现——比 RTOS 简单多了，但效果一样好。

——进阶补充——
I2C 多设备共总线设计要小心几个细节。第一是地址冲突——MPU6050 默认 0x68、SHT30 默认 0x44、BMP280 默认 0x76、SSD1306 默认 0x3C，全都不同所以可以共总线。但同一型号两颗就要靠 ADDR 引脚改地址（接地或接 VCC 给两个不同地址）。第二是上拉电阻——I2C 是开漏总线，必须有外部上拉到 3.3V，每条总线一对 4.7kΩ 上拉就行。第三是总线频率——慢设备（OLED 100kHz）和快设备（SHT30 1MHz）混用时要按最慢的来，标准模式 100kHz 是最稳妥的兼容值。第四是错误恢复——如果某颗设备挂掉拉低 SDA 让总线锁死，需要软件发送 9 个 SCL 脉冲让从机自动释放。这种细节工程项目里非常常见。

数据滤波和异常检测是这种监测系统的灵魂。温度湿度传感器读数会有 ±0.5°C 的随机抖动——直接显示会让用户觉得不稳定。处理办法是一阶 IIR 滤波 t_filt = 0.9 × t_filt_last + 0.1 × t_raw，让短期抖动平滑掉但长期变化追得上。异常检测加阈值——温度超 50°C 或低于 -10°C 触发声光报警，这是消防、冷链监测系统的标配。再进阶一档是趋势分析——10 分钟内温度涨 3°C 触发预警，这是智能恒温控制的核心算法。

最后聊扩展能力。这套系统天然能加 WiFi（ESP8266 通过 UART 串接）变 IoT 节点，加 NB-IoT 模组变远程监测，加 LoRa 变长距离感知节点。这就是现代嵌入式系统的伟大处——同样的传感器读取代码，配上不同通信模块就能落到不同应用场景。学生时代你做完这个项目，下一步就是让它说话——通过 MQTT 把数据传到云端、在手机上看实时曲线。这就是从硬件到软件到云的完整 IoT 链路。"""

