def main() -> int:
    ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..', '..'))
    M = os.path.join(ROOT, 'apps', 'player', 'public', 'manifest.json')
    targets = {
        'p7-adc':       ('p7-adc-dh',       P7_DH),
        'p11-band':     ('p11-band-dh',     P11_DH),
        'p12-suntrack': ('p12-suntrack-dh', P12_DH),
    }
    CN = re.compile(r"[\u4e00-\u9fa5]")
    with open(M, encoding='utf-8') as f:
        m = json.load(f)
    n = 0
    for ch in m.get('chapters', []):
        for s in ch.get('sections', []):
            for p in s.get('pages', []):
                pid = p.get('id', '')
                if pid not in targets:
                    continue
                bid_target, full_script = targets[pid]
                for b in p.get('blocks', []):
                    if b.get('id') != bid_target:
                        continue
                    b['script'] = full_script  # 整体替换占位符
                    total = len(CN.findall(full_script))
                    print(f'[OK]   {pid}/{bid_target} → {total} 字')
                    n += 1
    with open(M, 'w', encoding='utf-8') as f:
        json.dump(m, f, ensure_ascii=False, indent=2)
    print(f'[DONE] 替换 {n} 个 dh，manifest {os.path.getsize(M)//1024} KB')
    return n


if __name__ == '__main__':
    main()
