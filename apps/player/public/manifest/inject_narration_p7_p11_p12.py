P7_DH = """同学们好，这一节我们打开 STM32 感知世界的核心能力——ADC（模数转换器）。把光照、声音、温度、压力、电流、电压，把这些连续变化的物理量变成 MCU 能处理的数字，全都靠它。可以毫不夸张地说，没有 ADC 嵌入式系统就只是一堆数字逻辑，加上 ADC 它才有了感官，能感知世界。STM32F1 内嵌 12 位 SAR 型 ADC，最高采样率 1MSPS，对入门到中级嵌入式应用基本够用了。

12 位精度的意思是把一个 0 到 3.3V 的输入电压切成 4096 等份，每一份代表 3.3V / 4096 = 0.806 毫伏。这就是 ADC 的分辨率。读出来的数字 N 反推电压的公式是 V = N × 3.3 / 4095。比如 ADC 读到 2048，对应电压就是 1.65V——刚好是参考电压一半。掌握这个公式，ADC 工作的精髓你就握住了一半。

但是分辨率不等于精度。理论上 0.806 毫伏分辨率，实战中由于参考电压抖动、电源噪声、PCB 走线干扰、温度漂移，真正能信赖的可能只有 10 位甚至 9 位。提高 ADC 实际精度的工程手段有四个：第一是用低噪声 LDO 给 VDDA 单独供电、不要和数字电源混用；第二是 ADC 输入引脚旁就近放 100nF 滤波电容；第三是采样时间设到至少 13.5 个时钟以上，让内部采样保持电容充电充分；第四是软件做 4 到 16 次过采样平均，能在不动硬件的前提下再压一档噪声。学生时代你做实验只要做到第三和第四步，读数就能稳到 ±2LSB。

——进阶补充——
ADC 的三种工作模式各有适用场景。单次转换模式调一次 HAL_ADC_Start 转一次，CPU 要 polling ADC 完成中断或忙等结果——适合按键触发的偶发采样。连续转换模式启动后 ADC 一直转，每次转完结果存进数据寄存器，软件想读就读——适合周期性低频信号，比如温度计。扫描转换模式让 ADC 按顺序扫一组通道，配合 DMA 把每个通道结果直接搬进内存数组——多通道音频采集、电机三相电流采样的标准做法。

DMA 加 ADC 是嵌入式高级用法的入门门槛，但只要拆开看也不难：你把 DMA 设为外设到内存模式，源地址锁定 ADC1->DR，目标地址给一段 SRAM 缓冲区，再设 circular 模式 + ADC 在每次转换完触发 DMA。这套配齐 ADC 自己跑、DMA 自己搬，CPU 完全不参与，每秒能稳定采 100 万点而不丢一帧。这就是 ADC + DMA 让 STM32 在没有 RTOS 的情况下也能跑工业级数采的关键。

最后聊两个新手常踩的坑。第一是 ADC 引脚必须配置成 ANALOG 模式，不是 INPUT、不是 OUTPUT，是 ANALOG。配错了 GPIO 内部电路会拉走部分电流，读数偏移最多 50 毫伏。第二是 VREF 的稳定性。STM32F1 默认 VREF 接到 VDDA，VDDA 又接到 3.3V 数字电源——如果板子电源纹波大，所有 ADC 读数都会跟着抖。解决办法是把 VDDA 单独走一颗 LDO，或者外接 2.5V 高精度参考电压源。两个细节做到位你的 ADC 就从凑合用变成工业级。"""

